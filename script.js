// ==================== 状態管理 ====================
let selectedWorryId = null;
let selectedFollowUpIndex = null;

// ==================== 画面切り替え ====================
function showScreen(id) {
  document.querySelectorAll(".screen").forEach(el => el.classList.remove("active"));
  document.getElementById(id).classList.add("active");
  window.scrollTo(0, 0);
}

// ==================== 困りごとボタンを生成 ====================
function renderTopics() {
  const list = document.getElementById("topics-list");
  list.innerHTML = "";
  worries.forEach((worry) => {
    const btn = document.createElement("button");
    btn.className = "topic-btn";
    btn.type = "button";
    btn.innerHTML = `<span class="num">${worry.id}.</span>${worry.title}`;
    btn.addEventListener("click", () => {
      showResponse(worry.id);
    });
    list.appendChild(btn);
  });
}

// ==================== 段落テキストを描画する共通処理 ====================
function renderParagraphs(container, text) {
  container.innerHTML = "";
  text.split("\n\n").forEach(paragraph => {
    const p = document.createElement("p");
    p.textContent = paragraph;
    container.appendChild(p);
  });
}

// ==================== 最初の回答画面を表示 ====================
function showResponse(worryId) {
  const worry = worries.find(w => w.id === worryId);
  if (!worry) return;

  selectedWorryId = worryId;
  selectedFollowUpIndex = null;

  document.getElementById("response-worry-title").textContent = worry.title;
  renderParagraphs(document.getElementById("response-box"), worry.response);

  showScreen("screen-response");
}

// ==================== 深掘り選択肢画面を表示 ====================
function showFollowUpList() {
  const worry = worries.find(w => w.id === selectedWorryId);
  if (!worry || !worry.followUps || worry.followUps.length === 0) return;

  const list = document.getElementById("followup-list");
  list.innerHTML = "";
  worry.followUps.forEach((fu, index) => {
    const btn = document.createElement("button");
    btn.className = "topic-btn";
    btn.type = "button";
    btn.textContent = fu.title;
    btn.addEventListener("click", () => {
      showFollowUpResponse(index);
    });
    list.appendChild(btn);
  });

  showScreen("screen-followup");
}

// ==================== 深掘り追加回答画面を表示 ====================
function showFollowUpResponse(index) {
  const worry = worries.find(w => w.id === selectedWorryId);
  if (!worry || !worry.followUps || !worry.followUps[index]) return;

  selectedFollowUpIndex = index;
  const fu = worry.followUps[index];

  document.getElementById("followup-response-title").textContent = fu.title;
  renderParagraphs(document.getElementById("followup-response-box"), fu.response);

  showScreen("screen-followup-response");
}

